def test_alternate_observations_without_a_named_source_are_refused():
    """An unattributed observation cannot be keyed to a qualification slot.

    The whole qualification key exists to stop a measurement of one source being read
    as a measurement of another. A paired file that records a second source's verdicts
    without saying which source they came from reintroduces that hole at ingest.
    """
    with pytest.raises(ValueError, match="alternate source version"):
        _run((_case("a", True, "111", "111"),), alternate=False)


def test_the_run_id_changes_when_only_the_alternate_verdicts_change():
    """Two studies differing only in the alternate's verdicts are different studies.

    If the content digest ignored the alternate column, an artifact regenerated after
    re-running the alternate would keep the old id and the two would be indistinguishable
    -- which is the exact question the digest was added to answer.
    """
    first = _run((_case("a", True, "111", "111"),))
    second = _run((_case("a", True, "111", "000"),))
    assert first.run_id != second.run_id


def test_the_alternate_view_is_the_alternate_and_covers_paired_cases_only():
    """``alternate_view`` swaps the columns; it does not reinterpret them.

    Restricting to paired cases is load-bearing: an alternate sensitivity computed over
    a different case set than the primary's cannot be differenced against it, and the
    difference is the first thing anyone will compute.
    """
    run = _run(
        (
            _case("paired", True, "111", "000"),
            _case("unpaired", True, "111"),
        )
    )
    view = run.alternate_view()
    assert view.evaluator_version == SourceVersionRef("alt", "v1")
    assert view.alternate_version is None
    assert [c.case_id for c in view.cases] == ["paired"]
    assert view.cases[0].outcomes == (False, False, False)
    assert not view.cases[0].has_alternate
    #: Identity other than the source version is preserved: the alternate was measured
    #: on the same population against the same system.
    assert view.failure_mode == run.failure_mode
    assert view.population_id == run.population_id
    assert view.distribution_id == run.distribution_id


def test_an_alternate_artifact_keyed_to_the_alternate_refuses_the_primary_slot():
    """Fail-closed identity, inherited rather than reimplemented.

    The alternate's artifact goes through exactly the machinery the primary's does, so
    it gets the same refusal for free. Asserted here because "for free" is a claim about
    code that could stop being true.
    """
    run = replace(
        _run(
            tuple(
                _case(f"c{i}", i % 2 == 0, "111" if i % 2 == 0 else "000", "110")
                for i in range(10)
            )
        ),
        measured_on=date(2026, 9, 26),
    )
    document = artifact_document(characterize(run.alternate_view(), 0.05))
    assert document["identity"]["evaluator"] == "alt@v1"

    with pytest.raises(ArtifactIdentityError, match="source_version"):
        qualification_from_document(
            document,
            expected_key=QualificationKey(
                source_version=SourceVersionRef("primary", "v1"),
                failure_mode=FailureModeRef("MODE", "v1"),
                population_id="pop",
                distribution_id="dist",
            ),
        )


