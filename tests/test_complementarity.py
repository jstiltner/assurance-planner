def test_the_four_cells_count_what_their_names_say():
    """One case per cell, hand-checkable.

    ``111`` is a unanimous flag and ``000`` a unanimous pass, so on a
    reference-positive case ``111`` is correct and ``000`` is wrong. Four cases, four
    cells, and the order of the arguments is the thing most likely to be wrong.
    """
    table = paired_errors(
        (
            _case("both-right", True, "111", "111"),
            _case("primary-wrong", True, "000", "111"),
            _case("alternate-wrong", True, "111", "000"),
            _case("both-wrong", True, "000", "000"),
        )
    )
    assert table.neither_wrong == 1
    assert table.primary_only_wrong == 1
    assert table.alternate_only_wrong == 1
    assert table.both_wrong == 1
    assert table.decided == 4
    assert table.primary_errors == 2
    assert table.alternate_errors == 2


def test_an_unpaired_case_is_excluded_rather_than_counted_as_agreement():
    """The failure mode this guards is the quiet one.

    A case never sent to the alternate has no alternate verdict. Treating its absence
    as agreement would inflate ``neither_wrong`` on exactly the cases nobody looked at,
    which makes a partially-collected study look like a complete one.
    """
    table = paired_errors(
        (_case("paired", True, "111", "111"), _case("lonely", True, "000"))
    )
    assert table.unpaired == 1
    assert table.decided == 1
    assert table.neither_wrong == 1
    assert table.both_wrong == 0


def test_a_tie_on_either_side_removes_the_case_from_the_table():
    """A tie is not an answer, and resolving it here would invent an observation.

    Both directions are checked, because the asymmetric bug -- resolving the primary's
    ties but not the alternate's -- would silently make the primary look decisive.
    """
    primary_tie = paired_errors((_case("a", True, "10", "111"),))
    alternate_tie = paired_errors((_case("b", True, "111", "10"),))
    assert primary_tie.undecided == 1 and primary_tie.decided == 0
    assert alternate_tie.undecided == 1 and alternate_tie.decided == 0


def test_disagreement_equals_the_two_off_diagonal_cells():
    """An internal consistency identity, and it is not a tautology in the code.

    With binary verdicts and a shared reference label, the sources agree whenever they
    are both right and whenever they are both wrong, and disagree exactly when one is
    right. ``verdict_disagreements`` is counted from the verdicts and the off-diagonal
    cells are counted from correctness, by separate branches; if they ever disagree,
    one of the two is being computed against the wrong thing.
    """
    table = paired_errors(
        (
            _case("a", True, "111", "111"),
            _case("b", True, "000", "111"),
            _case("c", False, "111", "000"),
            _case("d", True, "000", "000"),
            _case("e", False, "000", "000"),
        )
    )
    assert table.verdict_disagreements == (
        table.primary_only_wrong + table.alternate_only_wrong
    )


