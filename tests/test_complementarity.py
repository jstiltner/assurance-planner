"""Tests for the alternate-source instrument.

Every assertion here is about **arithmetic or refusal**.  None is about the quality of
the alternate source in the paired fixture, because that fixture was generated by
``scripts/make_fixtures.py`` and any assertion about its alternate's accuracy would be an
assertion about a random number generator dressed as a finding.

The distinction is worth stating precisely, because it is easy to write the wrong test
here and it would look right:

* ``the recovery rate is 6/11`` -- fine.  It is a statement about the counting.
* ``the recovery rate is above 0.5`` -- not fine.  It is a statement about the generator
  that would read, to anyone scanning the suite, as support for the routing hypothesis.
"""

from __future__ import annotations

from dataclasses import replace
from datetime import date
from pathlib import Path

import pytest

from assurance_planner.artifacts import (
    ArtifactIdentityError,
    SyntheticArtifactError,
    artifact_document,
    qualification_from_document,
)
from assurance_planner.characterization import CaseRun, CharacterizationRun, characterize
from assurance_planner.complementarity import (
    POINT_ESTIMATE_FLOOR,
    Sufficiency,
    analyse_complementarity,
    errors_to_decide,
    paired_errors,
    required_paired_cases,
)
from assurance_planner.complementarity_report import UNMEASURED, render_complementarity
from assurance_planner.domain import FailureModeRef, QualificationKey, SourceVersionRef
from assurance_planner.loader import load_characterization

DATA = Path(__file__).resolve().parents[1] / "data"
PAIRED = DATA / "SYNTHETIC_paired_runs.yaml"


@pytest.fixture
def paired() -> CharacterizationRun:
    return load_characterization(PAIRED)


@pytest.fixture
def mixed() -> CharacterizationRun:
    """A pre-existing primary-only run, used to check what absence renders as."""
    return load_characterization(DATA / "judge_runs_mixed.yaml")


def _case(
    case_id: str,
    reference: bool,
    primary: str,
    alternate: str = "",
    slice_id: str = "s",
) -> CaseRun:
    return CaseRun(
        case_id=case_id,
        reference_label=reference,
        outcomes=tuple(c == "1" for c in primary),
        alternate_outcomes=tuple(c == "1" for c in alternate),
        slice_id=slice_id,
    )


def _run(cases: tuple[CaseRun, ...], alternate: bool = True) -> CharacterizationRun:
    return CharacterizationRun(
        evaluator_version=SourceVersionRef("primary", "v1"),
        failure_mode=FailureModeRef("MODE", "v1"),
        population_id="pop",
        distribution_id="dist",
        cases=cases,
        alternate_version=SourceVersionRef("alt", "v1") if alternate else None,
    )


