def test_the_paired_fixture_declares_itself_synthetic(paired):
    """The marker is structural, not prose.

    A ``limitations`` string is a footnote and footnotes get dropped when a table is
    pasted somewhere else. ``synthetic: true`` is a field that code branches on.
    """
    assert paired.synthetic is True
    assert PAIRED.name.startswith("SYNTHETIC_")
    assert "SYNTHETIC" in str(paired.alternate_version)
    assert any("SYNTHETIC" in limit for limit in paired.limitations)


def test_an_artifact_from_synthetic_observations_can_be_written_but_never_loaded(paired):
    """The loop that makes the synthetic fixture safe to keep in the repository.

    It has to be writable, because writing it is how the artifact machinery gets
    exercised on paired data. It must not be loadable, because a qualification artifact
    is a planner input and there is nothing behind this one.
    """
    document = artifact_document(characterize(paired.alternate_view(), 0.05))
    assert document["synthetic"] is True
    assert list(document)[:2] == ["schema", "synthetic"]

    with pytest.raises(SyntheticArtifactError):
        qualification_from_document(document)


def test_the_report_announces_synthetic_input_and_names_no_recommendation(paired):
    """Two properties of the report, and the second is the one under instruction.

    The banner is at the top. And every decision cell reads UNMEASURED -- there is no
    code path in the report module that writes anything else into one, so this holds for
    real data too until an artifact backs it.
    """
    analysis = analyse_complementarity(paired)
    text = render_complementarity(
        analysis,
        characterize(paired, 0.05),
        characterize(paired.alternate_view(), 0.05),
    )
    assert "SYNTHETIC DATA" in text.splitlines()[1]
    assert not analysis.measured

    for decision in (
        "Replace the primary",
        "Keep both, route selectively",
        "Reject the alternate",
    ):
        line = next(l for l in text.splitlines() if l.strip().startswith(decision))
        assert UNMEASURED in line, f"'{decision}' was given a verdict"

    #: No recommendation vocabulary anywhere in the document.
    lowered = text.lower()
    for word in ("recommend", "we should", "conclude that", "best option"):
        assert word not in lowered


def test_on_an_all_failures_corpus_disagreement_and_recovery_are_one_number():
    """The arithmetic behind the warning the statistics block prints unconditionally.

    Every case here has the primary wrong, which is what a failure-enriched corpus is.
    With binary verdicts against a shared reference the sources then disagree exactly
    when the alternate is right, so two statistics printed four lines apart under
    different names are the same quantity -- and the production disagreement rate,
    which this would be read as, is smaller by a factor of the primary error rate.

    Phi is already refused on this table, but by the empty-margin rule rather than by
    any understanding of the sampling: the primary-correct row is empty. That rule does
    not fire on a *partially* enriched corpus, where phi is a plausible number computed
    from reweighted cells. Nothing in the schema records the sampling design and no
    arithmetic recovers it, which is why the warning is prose and not a check.
    """
    table = paired_errors(
        tuple(_case(f"f{i}", True, "000", "111" if i < 7 else "000") for i in range(10))
    )
    assert table.primary_errors == table.decided == 10
    assert table.disagreement_rate.point == table.alternate_correct_given_primary_wrong.point
    assert table.error_association_phi is None


def test_the_report_warns_that_phi_and_disagreement_assume_representative_sampling(
    paired,
):
    text = render_complementarity(
        analyse_complementarity(paired),
        characterize(paired, 0.05),
        characterize(paired.alternate_view(), 0.05),
    )
    statistics = text.split("Complementarity statistics")[1].split("Is the recovery")[0]
    assert "Phi is not invariant to" in statistics
    assert "the same number under two names" in statistics


def test_the_report_separates_the_observation_the_interval_and_the_declared_threshold(
    paired,
):
    """Four lines, because they are four different kinds of thing.

    Collapsing them is exactly how an economic constant came to be printed in the
    register of a statistical convention. The first two are measurements, the third is
    a policy input and is labelled as one, and only the fourth is a claim -- a claim
    relative to the third rather than an absolute.
    """
    text = render_complementarity(
        analyse_complementarity(paired, 0.20),
        characterize(paired, 0.05),
        characterize(paired.alternate_view(), 0.05),
    )
    section = text.split("Is the recovery evidence sufficient")[1].split("Per slice")[0]
    assert "observed recovery" in section
    assert "statistical uncertainty" in section
    assert "declared break-even r*" in section
    assert "POLICY INPUT, not measured here" in section
    assert "decision support" in section

    #: The retraction is printed, not merely enacted: 0.5 appears only as the rule that
    #: was withdrawn, never as a comparison being made.
    assert "0.5 was an undeclared economic" in section


def test_without_a_declared_break_even_the_report_refuses_to_call_anything_sufficient(
    paired,
):
    """Descriptive statistics remain; the verdict does not.

    A study that was never told what would count as success has not failed to measure
    anything -- it has been asked no question. The report has to render that as a
    missing input rather than as a weak result or, worse, as a passing one.
    """
    analysis = analyse_complementarity(paired)
    text = render_complementarity(
        analysis, characterize(paired, 0.05), characterize(paired.alternate_view(), 0.05)
    )
    assert analysis.recovery_sufficiency is Sufficiency.UNDECLARED
    assert "UNDECLARED  (none supplied; this is an input, not a measurement)" in text
    assert "NOT DECISION-SUFFICIENT" in text
    #: Still reports the observation and its uncertainty.
    assert "0.545" in text and "[0.280, 0.787]" in text


def test_a_single_source_run_reports_unmeasured_rather_than_zero_complementarity(mixed):
    """Absence of data is not a low reading, and the report must not render it as one.

    ``data/judge_runs_mixed.yaml`` has no alternate column at all. A recovery rate of
    0.000 printed against it would be false in the direction that kills a hypothesis
    for the wrong reason.
    """
    analysis = analyse_complementarity(mixed)
    assert not analysis.has_paired_data
    text = render_complementarity(analysis, characterize(mixed, 0.05), None)
    assert "No paired observations." in text
    assert "Complementarity is not low here" in text
    assert UNMEASURED in text


